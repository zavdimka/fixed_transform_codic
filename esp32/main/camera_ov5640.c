static const char *TAG = "camera_ov5640";
static i2c_master_bus_handle_t s_bus;
static i2c_master_dev_handle_t s_device;

esp_err_t camera_ov5640_start(void)
{
    if (s_device != NULL) {
        return ESP_OK;
    }

    const i2c_master_bus_config_t bus_config = {
        .i2c_port = I2C_NUM_0,
        .sda_io_num = BOARD_PIN_TWI_SDA,
        .scl_io_num = BOARD_PIN_TWI_SCK,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = false,
    };
    esp_err_t err = i2c_new_master_bus(&bus_config, &s_bus);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "cannot initialize SCCB bus: %s",
                 esp_err_to_name(err));
        return err;
    }

    err = i2c_master_probe(s_bus, CAMERA_I2C_ADDRESS, 100);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "no response at SCCB address 0x%02x: %s",
                 CAMERA_I2C_ADDRESS, esp_err_to_name(err));
        return err;
    }

    const i2c_device_config_t device_config = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = CAMERA_I2C_ADDRESS,
        .scl_speed_hz = CAMERA_I2C_CLOCK_HZ,
    };
    err = i2c_master_bus_add_device(s_bus, &device_config, &s_device);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "cannot add OV5640 SCCB device: %s",
                 esp_err_to_name(err));
    }
    return err;
}

esp_err_t camera_ov5640_read_register(uint16_t address, uint8_t *value)
{
    if (value == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    esp_err_t err = camera_ov5640_start();
    if (err != ESP_OK) {
        return err;
    }
    const uint8_t register_address[] = {
        (uint8_t)(address >> 8), (uint8_t)address,
    };
    return i2c_master_transmit_receive(s_device, register_address,
                                       sizeof(register_address), value, 1, 100);
}

esp_err_t camera_ov5640_probe(uint16_t *chip_id)
{
    uint8_t high = 0;
    uint8_t low = 0;
    esp_err_t err = camera_ov5640_read_register(OV5640_CHIP_ID_HIGH, &high);
    if (err == ESP_OK) {
        err = camera_ov5640_read_register(OV5640_CHIP_ID_LOW, &low);
    }
    if (err == ESP_OK) {
        const uint16_t id = ((uint16_t)high << 8) | low;
        if (chip_id != NULL) {
            *chip_id = id;
        }
        ESP_LOGI(TAG, "SCCB responded, chip ID=0x%04x", id);
        if (id != 0x5640) {
            err = ESP_ERR_NOT_FOUND;
        }
    }
    return err;
}

static esp_err_t camera_ov5640_write_register(uint16_t address, uint8_t value)
{
    esp_err_t err = camera_ov5640_start();
    if (err != ESP_OK) {
        return err;
    }
    const uint8_t command[] = {
        (uint8_t)(address >> 8), (uint8_t)address, value,
    };
    return i2c_master_transmit(s_device, command, sizeof(command), 100);
}

esp_err_t camera_ov5640_set_test_pattern(bool enabled)
{
    return camera_ov5640_write_register(0x503d, enabled ? 0x80 : 0x00);
}

esp_err_t camera_ov5640_set_yuv_order(uint8_t order)
{
    if (order > 3) {
        return ESP_ERR_INVALID_ARG;
    }
    return camera_ov5640_write_register(0x4300, 0x30 | order);
}
esp_err_t camera_ov5640_set_hts(uint16_t hts)
{
    // 1896 is the native 1280x720 line length for this PLL setup. Smaller
    // values would truncate horizontal blanking and are intentionally rejected.
    if (hts < 1896) {
        return ESP_ERR_INVALID_ARG;
    }
    esp_err_t err =
        camera_ov5640_write_register(0x380c, (uint8_t)(hts >> 8));
    if (err == ESP_OK) {
        err = camera_ov5640_write_register(0x380d, (uint8_t)hts);
    }
    return err;
}
esp_err_t camera_ov5640_configure_720p(void)
{
    uint16_t chip_id = 0;
    esp_err_t err = camera_ov5640_probe(&chip_id);
    if (err != ESP_OK) {
        return err;
    }

    err = camera_ov5640_write_register(0x3008, 0x82);
    if (err != ESP_OK) {
        return err;
    }
    vTaskDelay(pdMS_TO_TICKS(20));

    for (size_t index = 0;
         index < sizeof(s_common_isp) / sizeof(s_common_isp[0]); ++index) {
        err = camera_ov5640_write_register(s_common_isp[index].address,
                                           s_common_isp[index].value);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "common register 0x%04x failed at index %u: %s",
                     s_common_isp[index].address, (unsigned)index,
                     esp_err_to_name(err));
            return err;
        }
    }

    for (size_t index = 0;
         index < sizeof(s_dvp_720p) / sizeof(s_dvp_720p[0]); ++index) {
        err = camera_ov5640_write_register(s_dvp_720p[index].address,
                                           s_dvp_720p[index].value);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "register 0x%04x failed at index %u: %s",
                     s_dvp_720p[index].address, (unsigned)index,
                     esp_err_to_name(err));
            return err;
        }
    }
    vTaskDelay(pdMS_TO_TICKS(100));
    ESP_LOGI(TAG, "configured 1280x720 YUV422 DVP");
    return ESP_OK;
}
